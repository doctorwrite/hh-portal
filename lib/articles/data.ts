// ===== ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ =====
export function getArticle(slug: string): ArticleData | undefined {
  return ARTICLES[slug]
}

export function getAllArticleSlugs(): string[] {
  return Object.keys(ARTICLES)
}

export function searchArticles(query: string): Array<{ slug: string; title: string }> {
  const q = query.toLowerCase().trim()
  if (!q) return []
  return Object.entries(ARTICLES)
    .filter(([_, article]) => article.title.toLowerCase().includes(q))
    .map(([slug, article]) => ({ slug, title: article.title }))
}
